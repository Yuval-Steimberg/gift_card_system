function renderBlock(block: Block, i: number) {
  if (typeof block === 'string') {
    return (
      <p key={i} className="whitespace-pre-line">
        {block}
      </p>
    )
  }
  return (
    <ul key={i} className="list-disc space-y-1.5 pe-5">
      {block.list.map((item, j) => (
        <li key={j}>{item}</li>
      ))}
    </ul>
  )
}

